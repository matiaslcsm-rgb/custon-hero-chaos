// Encastra las capas de un cuadro en filas como las del resto de HERO_ART (17 × 24, '.' = vacío)
function heroPartsCompose(layers) {
    const out = Array.from({ length: 24 }, () => Array(17).fill('.'));
    const put = (rows, ox, oy) => rows.forEach((r, y) => [...r].forEach((ch, x) => {
        if (ch !== '.' && out[oy + y] && x + ox >= 0 && x + ox < 17) out[oy + y][x + ox] = ch;
    }));
    layers.forEach(([name, a, b]) => {
        const P = HERO_PARTS.body[name], W = HERO_PARTS.weapons[name];
        if (P) put(P.rows, a, P.y + b); else put(W.rows, a - W.gx, b - W.gy);
    });
    return out.map(r => r.join(''));
}
